"""업종 공통 법정 금지어 — 오퍼가 안 적어 줘도 법은 적용된다.

실제 오퍼 7건 중 **3건은 금지사항이 아예 없었다**(이사스토리·현금사은품·
카바딜러). 안전해서가 아니라 안 적어 준 것이다. 게다가 그 오퍼들의 소개문에
"전국 최대", "최저요금", "무료로" 같은 표현이 그대로 있다.

**다만 일괄 적용하면 안 된다.** 같은 낱말이 오퍼마다 갈린다(실측 충돌 10건).

    '최고'  중정·서앤율·안과는 금지   ↔  이사스토리는 "최고 20%까지 절약"
    '전문'  중정·서앤율·안과는 금지   ↔  이사스토리는 "친절하고 전문적입니다"

그래서 여기 있는 것은 **법정 금지**만이다. 업종이 걸릴 때만 붙이고,
오퍼 규칙과 부딪히면 사람에게 알린다.
"""
from __future__ import annotations

from typing import Dict, List, Tuple

# 업종 판별 — 오퍼 원문에 이 말이 있으면 그 업종으로 본다
VERTICAL_HINTS: Dict[str, Tuple[str, ...]] = {
    "medical": ("병원", "의원", "안과", "치과", "성형", "시술", "수술",
                "진료", "환자", "의료진", "라식", "라섹"),
    "legal": ("법무법인", "변호사", "법률사무소", "소송", "개인회생",
              "파산", "이혼", "형사"),
    "finance": ("대출", "금리", "한도", "상환", "담보", "스탁론", "증권",
                "보험", "연금", "카드사"),
    "health_food": ("건강기능식품", "영양제", "다이어트", "체지방", "면역"),
}

# 법정 금지 표현. 업종별로 근거가 다르다.
LEGAL_BANS: Dict[str, List[Tuple[str, str]]] = {
    # 의료법 제56조 — 과장·비교·최상급·치료경험담
    "medical": [
        ("최고", "의료법 제56조 — 최상급 표현"),
        ("최상", "의료법 제56조 — 최상급 표현"),
        ("1위", "의료법 제56조 — 비교·우위 표현"),
        ("부작용 없", "의료법 제56조 — 확신·보장 표현"),
        ("100% 보장", "의료법 제56조 — 확신·보장 표현"),
        ("완치", "의료법 제56조 — 치료효과 오인"),
    ],
    # 변호사 광고에 관한 규정 — 객관적으로 확인 불가한 표현
    "legal": [
        ("승소율", "변호사 광고 규정 — 확인 불가 수치"),
        ("100% 환불", "변호사 광고 규정 — 확신 표현"),
        ("무조건", "변호사 광고 규정 — 확신 표현"),
    ],
    # 표시광고법·금융광고 규제 — 단정·최상급
    "finance": [
        ("무조건 승인", "금융광고 규제 — 확신 표현"),
        ("누구나 가능", "금융광고 규제 — 확신 표현"),
        ("100% 승인", "금융광고 규제 — 확신 표현"),
    ],
    # 건강기능식품법 — 질병 예방·치료 표방
    "health_food": [
        ("치료", "건강기능식품법 — 질병 치료 표방"),
        ("질병 예방", "건강기능식품법 — 질병 예방 표방"),
        ("효능", "건강기능식품법 — 의약품 오인"),
    ],
}

# 업종과 무관하게 표시광고법에 걸릴 수 있는 단정 표현.
# **경고만 한다.** 차단하면 광고주가 준 문구까지 막힌다.
GENERIC_WARN = ("무조건", "100%", "절대", "완벽", "유일무이")


def verticals_in(text: str) -> List[str]:
    """원문이 어느 업종에 걸리나. 여러 개일 수 있다."""
    body = (text or "").replace(" ", "")
    return [name for name, hints in VERTICAL_HINTS.items()
            if any(hint in body for hint in hints)]


def legal_rules(verticals: List[str]) -> List[dict]:
    """업종 법정 금지를 규칙 형태로.

    오퍼가 안 적어 준 것을 메운다. 출처를 남겨 왜 막혔는지 알 수 있게 한다.
    """
    out: List[dict] = []
    for vertical in verticals or []:
        for word, why in LEGAL_BANS.get(vertical, []):
            out.append({
                "type": "must_not_include", "scope": "all",
                "target": "표현", "value": word,
                "source_quote": f"[법정] {why}",
                "severity": "block",
            })
    return out


def generic_warnings() -> List[dict]:
    """업종 무관 경고. 차단이 아니라 경고다."""
    return [{
        "type": "must_not_include", "scope": "all", "target": "표현",
        "value": word, "source_quote": "[법정] 표시광고법 — 단정 표현",
        "severity": "warn",
    } for word in GENERIC_WARN]
